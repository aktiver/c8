//! Bounded-memory, topology-independent compilation of verified cloud RDF fragments.
//!
//! Phase 40.13.12 consumes the checksum-bound N-Quads handoff created by the
//! cloud source decoder. It never lists a bucket, accepts credentials, aligns
//! raw data, authorizes graphs, or activates a snapshot. Kubernetes pod count
//! changes scheduling only: immutable fragment ordinals and logical partition
//! IDs determine every output byte.

