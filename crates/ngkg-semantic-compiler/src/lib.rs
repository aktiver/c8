/// Fail-closed semantic compiler failures.
#[derive(Debug, Error)]
pub enum SemanticCompilerError {
    #[error("semantic compiler I/O failed: {0}")]
    Io(#[from] std::io::Error),
    #[error("semantic compiler JSON failed: {0}")]
    Json(#[from] serde_json::Error),
    #[error("semantic compiler RDF failed: {0}")]
    Rdf(String),
    #[error("semantic compiler Arrow failed: {0}")]
    Arrow(#[from] arrow_schema::ArrowError),
    #[error("semantic compiler Parquet failed: {0}")]
    Parquet(#[from] parquet::errors::ParquetError),
    #[error("semantic compiler contract failed: {0}")]
    Contract(String),
    #[error("immutable output already exists: {0}")]
    ImmutableConflict(PathBuf),
}

/// Validate the complete Phase 40.13.11 handoff before scheduling any work.
pub fn validate_handoff(
    handoff: &CompilerHandoffManifest,
) -> Result<(), SemanticCompilerError> {
    if handoff.format_version != 1
        || handoff.decoded_format != "application/n-quads"
        || handoff.blank_node_policy != "object-scoped-label-v1"
        || handoff.logical_partitions == 0
        || handoff.logical_partitions > 65_536
        || handoff.total_objects == 0
        || handoff.total_quads == 0
        || handoff.expected_completions != handoff.verified_completions
    {
        return Err(SemanticCompilerError::Contract(
            "compiler handoff header or completion barrier is invalid".to_owned(),
        ));
    }
    for checksum in [
        &handoff.source_manifest_sha256,
        &handoff.decode_plan_sha256,
        &handoff.aggregate_source_sha256,
        &handoff.completion_set_sha256,
    ] {
        require_sha256(checksum)?;
    }
    if handoff.fragments.len() != usize::try_from(handoff.total_objects).unwrap_or(usize::MAX) {
        return Err(SemanticCompilerError::Contract(
            "handoff fragment count is not totalObjects".to_owned(),
        ));
    }
    let mut bytes = 0_u64;
    let mut quads = 0_u64;
    for (index, fragment) in handoff.fragments.iter().enumerate() {
        if usize::try_from(fragment.ordinal).ok() != Some(index)
            || !valid_blank_scope(&fragment.blank_node_scope, fragment.ordinal)
        {
            return Err(SemanticCompilerError::Contract(
                "handoff fragment ordinals or blank-node scopes are invalid".to_owned(),
            ));
        }
        require_sha256(&fragment.source_sha256)?;
        require_sha256(&fragment.sha256)?;
        bytes = bytes.checked_add(fragment.bytes).ok_or_else(|| {
            SemanticCompilerError::Contract("fragment byte total overflow".to_owned())
        })?;
        quads = quads.checked_add(fragment.quad_count).ok_or_else(|| {
            SemanticCompilerError::Contract("fragment quad total overflow".to_owned())
        })?;
    }
    if bytes != handoff.total_bytes || quads != handoff.total_quads {
        return Err(SemanticCompilerError::Contract(
            "handoff fragment totals do not match the barrier".to_owned(),
        ));
    }
    Ok(())
}

/// Map one verified decoded fragment into bounded, sorted logical-partition runs.
pub fn map_fragment(
    handoff: &CompilerHandoffManifest,
    handoff_sha256: &str,
    fragment_ordinal: u32,
    fragment_path: &Path,
    output_root: &Path,
    limits: MapLimits,
) -> Result<PathBuf, SemanticCompilerError> {
    validate_handoff(handoff)?;
    require_sha256(handoff_sha256)?;
    if limits.max_fragment_bytes == 0
        || limits.max_fragment_quads == 0
        || limits.max_rows_in_memory == 0
        || limits.max_run_bytes == 0
        || limits.worker_threads == 0
    {
        return Err(SemanticCompilerError::Contract(
            "map resource limits must be positive".to_owned(),
        ));
    }
    let fragment = handoff
        .fragments
        .get(usize::try_from(fragment_ordinal).map_err(|_| {
            SemanticCompilerError::Contract("fragment ordinal overflow".to_owned())
        })?)
        .filter(|value| value.ordinal == fragment_ordinal)
        .ok_or_else(|| SemanticCompilerError::Contract("fragment is absent".to_owned()))?;
    verify_file(fragment_path, &fragment.sha256, Some(fragment.bytes))?;
    if fragment.bytes > limits.max_fragment_bytes || fragment.quad_count > limits.max_fragment_quads {
        return Err(SemanticCompilerError::Contract(
            "fragment exceeds configured map ceiling".to_owned(),
        ));
    }
    ensure_new_root(output_root)?;
    let partition_count = usize::try_from(handoff.logical_partitions)
        .map_err(|_| SemanticCompilerError::Contract("partition count overflow".to_owned()))?;
    let mut buffers = vec![Vec::<String>::new(); partition_count];
    let mut term_buffer = Vec::<String>::new();
    let mut fact_runs = BTreeMap::<u32, Vec<RunArtifact>>::new();
    let mut term_runs = Vec::<RunArtifact>::new();
    let mut quad_count = 0_u64;
    let mut run_ordinal = 0_u32;
    let mut term_run_ordinal = 0_u32;
    let mut batch = Vec::with_capacity(limits.max_rows_in_memory);
    for line in BufReader::new(File::open(fragment_path)?).lines() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        batch.push(line);
        if batch.len() == limits.max_rows_in_memory {
            process_map_batch(
                &batch,
                &fragment.blank_node_scope,
                handoff.logical_partitions,
                limits.worker_threads,
                &mut buffers,
                &mut term_buffer,
            )?;
            quad_count = checked_add(
                quad_count,
                u64::try_from(batch.len()).map_err(|_| {
                    SemanticCompilerError::Contract("batch row count overflow".to_owned())
                })?,
                "mapped quad",
            )?;
            if quad_count > limits.max_fragment_quads {
                return Err(SemanticCompilerError::Contract(
                    "fragment exceeded quad ceiling while parsing".to_owned(),
                ));
            }
            flush_fact_buffers(output_root, &mut buffers, &mut fact_runs, &mut run_ordinal)?;
            flush_term_buffer(
                output_root,
                &mut term_buffer,
                &mut term_runs,
                &mut term_run_ordinal,
            )?;
            batch.clear();
        }
    }
    if !batch.is_empty() {
        process_map_batch(
            &batch,
            &fragment.blank_node_scope,
            handoff.logical_partitions,
            limits.worker_threads,
            &mut buffers,
            &mut term_buffer,
        )?;
        quad_count = checked_add(
            quad_count,
            u64::try_from(batch.len()).map_err(|_| {
                SemanticCompilerError::Contract("batch row count overflow".to_owned())
            })?,
            "mapped quad",
        )?;
    }
    flush_fact_buffers(
        output_root,
        &mut buffers,
        &mut fact_runs,
        &mut run_ordinal,
    )?;
    flush_term_buffer(
        output_root,
        &mut term_buffer,
        &mut term_runs,
        &mut term_run_ordinal,
    )?;
    if quad_count != fragment.quad_count {
        return Err(SemanticCompilerError::Contract(
            "mapped quad count differs from verified fragment".to_owned(),
        ));
    }
    let unique_quad_count = fact_runs
        .values()
        .flatten()
        .try_fold(0_u64, |total, run| total.checked_add(run.row_count))
        .ok_or_else(|| SemanticCompilerError::Contract("unique quad count overflow".to_owned()))?;
    if fact_runs
        .values()
        .flatten()
        .chain(term_runs.iter())
        .any(|run| run.bytes > limits.max_run_bytes)
    {
        return Err(SemanticCompilerError::Contract(
            "map spill run exceeds configured byte ceiling".to_owned(),
        ));
    }
    let manifest = FragmentMapManifest {
        format_version: SEMANTIC_COMPILER_FORMAT_VERSION,
        dataset_id: handoff.dataset_id,
        snapshot_id: handoff.target_snapshot_id,
        compiler_handoff_sha256: handoff_sha256.to_owned(),
        aggregate_source_sha256: handoff.aggregate_source_sha256.clone(),
        fragment_ordinal,
        fragment_sha256: fragment.sha256.clone(),
        blank_node_scope: fragment.blank_node_scope.clone(),
        logical_partitions: handoff.logical_partitions,
        input_quad_count: quad_count,
        unique_quad_count,
        fact_runs,
        term_runs,
    };
    let manifest_path = output_root.join("fragment-map.json");
    write_json_new(&manifest_path, &manifest)?;
    sync_directory(output_root)?;
    Ok(manifest_path)
}

fn process_map_batch(
    lines: &[String],
    blank_node_scope: &str,
    logical_partitions: u32,
    worker_threads: usize,
    buffers: &mut [Vec<String>],
    terms: &mut Vec<String>,
) -> Result<(), SemanticCompilerError> {
    let lanes = worker_threads.min(lines.len()).max(1);
    let chunk_size = lines.len().div_ceil(lanes);
    let results = std::thread::scope(|scope| {
        let handles = lines
            .chunks(chunk_size)
            .map(|chunk| {
                scope.spawn(move || {
                    let mut output = Vec::with_capacity(chunk.len());
                    for line in chunk {
                        let mut parser = RdfParser::from_format(RdfFormat::NQuads)
                            .for_slice(line.as_bytes());
                        let quad = parser
                            .next()
                            .ok_or_else(|| {
                                SemanticCompilerError::Rdf("empty N-Quads statement".to_owned())
                            })?
                            .map_err(|error| SemanticCompilerError::Rdf(error.to_string()))?;
                        if parser.next().is_some() {
                            return Err(SemanticCompilerError::Rdf(
                                "decoded line contains multiple N-Quads statements".to_owned(),
                            ));
                        }
                        let scoped = scope_quad(quad, blank_node_scope)?;
                        let canonical = format!("{scoped}\n");
                        let partition = partition_for(canonical.as_bytes(), logical_partitions)?;
                        let mut dictionary_terms = Vec::with_capacity(4);
                        collect_dictionary_terms(&scoped, &mut dictionary_terms);
                        output.push((partition, canonical, dictionary_terms));
                    }
                    Ok::<_, SemanticCompilerError>(output)
                })
            })
            .collect::<Vec<_>>();
        handles
            .into_iter()
            .map(|handle| {
                handle.join().map_err(|_| {
                    SemanticCompilerError::Contract("map parser lane terminated".to_owned())
                })?
            })
            .collect::<Result<Vec<_>, SemanticCompilerError>>()
    })?;
    for (partition, line, dictionary_terms) in results.into_iter().flatten() {
        let index = usize::try_from(partition).map_err(|_| {
            SemanticCompilerError::Contract("partition index overflow".to_owned())
        })?;
        buffers[index].push(line);
        terms.extend(dictionary_terms);
    }
    Ok(())
}

/// Verify all map completions and build one canonical dense RDF dictionary.
pub fn finalize_dictionary(
    handoff: &CompilerHandoffManifest,
    handoff_sha256: &str,
    map_manifest_paths: &[PathBuf],
    output_root: &Path,
) -> Result<PathBuf, SemanticCompilerError> {
    validate_handoff(handoff)?;
    require_sha256(handoff_sha256)?;
    let maps = load_complete_maps(handoff, handoff_sha256, map_manifest_paths)?;
    ensure_new_root(output_root)?;
    let mut term_paths = Vec::new();
    let mut completion_hasher = Sha256::new();
    completion_hasher.update(b"ngkg-semantic-map-completion-set-v1\0");
    for (path, manifest) in &maps {
        completion_hasher.update(manifest.fragment_ordinal.to_be_bytes());
        completion_hasher.update(decode_sha256(&sha256_path(path)?)?);
        let parent = path.parent().ok_or_else(|| {
            SemanticCompilerError::Contract("map manifest has no parent".to_owned())
        })?;
        for run in &manifest.term_runs {
            let run_path = safe_join(parent, &run.relative_path)?;
            verify_file(&run_path, &run.sha256, Some(run.bytes))?;
            term_paths.push(run_path);
        }
    }
    let dictionary_path = output_root.join("dictionary.tsv");
    let term_count = merge_terms_to_dictionary(&term_paths, &dictionary_path)?;
    let dictionary_sha256 = sha256_path(&dictionary_path)?;
    let guid_dictionary_path = output_root.join("guid-dictionary.tsv");
    let entity_count = write_guid_dictionary(
        &dictionary_path,
        &guid_dictionary_path,
        handoff.dataset_id,
    )?;
    let manifest = DictionaryManifest {
        format_version: SEMANTIC_COMPILER_FORMAT_VERSION,
        dataset_id: handoff.dataset_id,
        snapshot_id: handoff.target_snapshot_id,
        compiler_handoff_sha256: handoff_sha256.to_owned(),
        map_completion_set_sha256: hex::encode(completion_hasher.finalize()),
        dictionary_path: "dictionary.tsv".to_owned(),
        dictionary_sha256,
        term_count,
        guid_dictionary_path: "guid-dictionary.tsv".to_owned(),
        guid_dictionary_sha256: sha256_path(&guid_dictionary_path)?,
        entity_count,
        verified_map_completions: handoff.total_objects,
    };
    let path = output_root.join("dictionary-manifest.json");
    write_json_new(&path, &manifest)?;
    sync_directory(output_root)?;
    Ok(path)
}

/// Reduce every mapped run for one logical partition into query storage artifacts.
#[allow(clippy::too_many_arguments)]
pub fn reduce_partition(
    handoff: &CompilerHandoffManifest,
    handoff_sha256: &str,
    map_manifest_paths: &[PathBuf],
    dictionary_manifest_path: &Path,
    dictionary_manifest_sha256: &str,
    partition_index: u32,
    output_root: &Path,
    limits: ReduceLimits,
) -> Result<PathBuf, SemanticCompilerError> {
    validate_handoff(handoff)?;
    if partition_index >= handoff.logical_partitions
        || limits.max_input_runs == 0
        || limits.max_partition_quads == 0
        || limits.parquet_row_group_rows == 0
    {
        return Err(SemanticCompilerError::Contract(
            "partition index or reducer limits are invalid".to_owned(),
        ));
    }
    let maps = load_complete_maps(handoff, handoff_sha256, map_manifest_paths)?;
    verify_file(dictionary_manifest_path, dictionary_manifest_sha256, None)?;
    let dictionary_manifest: DictionaryManifest =
        serde_json::from_slice(&fs::read(dictionary_manifest_path)?)?;
    if dictionary_manifest.compiler_handoff_sha256 != handoff_sha256
        || dictionary_manifest.verified_map_completions != handoff.total_objects
    {
        return Err(SemanticCompilerError::Contract(
            "dictionary manifest is not bound to the complete map barrier".to_owned(),
        ));
    }
    let dictionary_root = dictionary_manifest_path.parent().ok_or_else(|| {
        SemanticCompilerError::Contract("dictionary manifest has no parent".to_owned())
    })?;
    let dictionary_path = safe_join(dictionary_root, &dictionary_manifest.dictionary_path)?;
    verify_file(
        &dictionary_path,
        &dictionary_manifest.dictionary_sha256,
        None,
    )?;
    let mut fact_paths = Vec::new();
    for (path, manifest) in &maps {
        let parent = path.parent().ok_or_else(|| {
            SemanticCompilerError::Contract("map manifest has no parent".to_owned())
        })?;
        if let Some(runs) = manifest.fact_runs.get(&partition_index) {
            for run in runs {
                let run_path = safe_join(parent, &run.relative_path)?;
                verify_file(&run_path, &run.sha256, Some(run.bytes))?;
                fact_paths.push(run_path);
            }
        }
    }
    if fact_paths.len() > limits.max_input_runs {
        return Err(SemanticCompilerError::Contract(
            "partition fan-in exceeds reducer run ceiling".to_owned(),
        ));
    }
    ensure_new_root(output_root)?;
    let canonical_path = output_root.join("facts.nq");
    let shuffle_merge_root = output_root.join("shuffle-merge");
    let (fact_count, duplicate_fact_count) = hierarchical_merge_unique(
        &fact_paths,
        &canonical_path,
        limits.max_partition_quads,
        &shuffle_merge_root,
    )?;
    if shuffle_merge_root.exists() {
        fs::remove_dir_all(&shuffle_merge_root)?;
    }
    let dictionary = build_partition_dictionary(
        &canonical_path,
        &dictionary_path,
        &output_root.join("dictionary-work"),
        limits.parquet_row_group_rows,
    )?;
    let parquet_path = output_root.join("facts.parquet");
    let adjacency_forward_path = output_root.join("adjacency-forward.tsv");
    let adjacency_reverse_path = output_root.join("adjacency-reverse.tsv");
    let semantic_index_path = output_root.join("semantic-index.tsv");
    let graph_inventory_path = output_root.join("graph-inventory.json");
    let output = build_partition_artifacts(
        &canonical_path,
        &dictionary,
        &parquet_path,
        &adjacency_forward_path,
        &adjacency_reverse_path,
        &semantic_index_path,
        partition_index,
        limits.parquet_row_group_rows,
    )?;
    fs::remove_dir_all(output_root.join("dictionary-work"))?;
    if output.fact_count != fact_count {
        return Err(SemanticCompilerError::Contract(
            "Parquet row count differs from canonical partition".to_owned(),
        ));
    }
    write_json_new(&graph_inventory_path, &output.graph_inventory)?;
    let artifacts = [
        "facts.nq",
        "facts.parquet",
        "adjacency-forward.tsv",
        "adjacency-reverse.tsv",
        "semantic-index.tsv",
        "graph-inventory.json",
    ]
    .into_iter()
    .map(|name| artifact(output_root, name))
    .collect::<Result<Vec<_>, _>>()?;
    let partition_id = partition_identity(
        handoff.dataset_id,
        handoff.target_snapshot_id,
        &handoff.aggregate_source_sha256,
        partition_index,
    );
    let manifest = SemanticPartitionManifest {
        format_version: SEMANTIC_COMPILER_FORMAT_VERSION,
        dataset_id: handoff.dataset_id,
        snapshot_id: handoff.target_snapshot_id,
        compiler_handoff_sha256: handoff_sha256.to_owned(),
        dictionary_sha256: dictionary_manifest.dictionary_sha256,
        partition_index,
        partition_id,
        input_run_count: u32::try_from(fact_paths.len()).map_err(|_| {
            SemanticCompilerError::Contract("input run count overflow".to_owned())
        })?,
        fact_count,
        duplicate_fact_count,
        edge_count: output.edge_count,
        class_assertion_count: output.class_assertion_count,
        artifacts,
        graph_inventory: output.graph_inventory,
        semantic_content_sha256: sha256_path(&canonical_path)?,
    };
    let manifest_path = output_root.join("semantic-partition.json");
    write_json_new(&manifest_path, &manifest)?;
    sync_directory(output_root)?;
    Ok(manifest_path)
}

/// Prove exact partition coverage and publish one inactive semantic root.
pub fn finalize_semantic_root(
    handoff: &CompilerHandoffManifest,
    handoff_sha256: &str,
    dictionary_manifest_path: &Path,
    dictionary_manifest_sha256: &str,
    partition_manifest_paths: &[PathBuf],
    output_root: &Path,
) -> Result<PathBuf, SemanticCompilerError> {
    finalize_semantic_root_inner(
        handoff,
        handoff_sha256,
        dictionary_manifest_path,
        dictionary_manifest_sha256,
        partition_manifest_paths,
        output_root,
        true,
    )
}

/// Finalize partition manifests whose artifacts were independently verified in
/// immutable object storage. This prevents the barrier pod from downloading all
